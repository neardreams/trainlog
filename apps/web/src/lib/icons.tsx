// 圖示：統一使用 lucide-react，className="i" 套用 v14 的尺寸與線寬（方頭線）
import {
  Activity,
  ArrowDown,
  ArrowLeft,
  ArrowRight,
  ArrowUp,
  ArrowUpDown,
  Calendar,
  ChartColumn,
  Check,
  ChevronDown,
  ChevronLeft,
  ChevronRight,
  ChevronsDownUp,
  ChevronsUpDown,
  Clock,
  Columns2,
  Download,
  ExternalLink,
  Dumbbell,
  FileText,
  History,
  House,
  Info,
  Flame,
  Funnel,
  LayoutGrid,
  List,
  Menu,
  Moon,
  PanelLeft,
  Shapes,
  Play,
  Rows3,
  Rows4,
  Search,
  Sun,
  Trophy,
  VideoOff,
  Volume2,
  X,
  type LucideIcon,
} from 'lucide-react';

const ICONS = {
  logo: Activity,
  grid: LayoutGrid,
  list: List,
  calendar: Calendar,
  search: Search,
  expand: ChevronsUpDown,
  collapse: ChevronsDownUp,
  left: ChevronLeft,
  right: ChevronRight,
  down: ChevronDown,
  back: ArrowLeft,
  chart: ChartColumn,
  compare: Columns2,
  doc: FileText,
  download: Download,
  filter: Funnel,
  x: X,
  check: Check,
  menu: Menu,
  panel: PanelLeft,
  sun: Sun,
  moon: Moon,
  rows: Rows3,
  rows2: Rows4,
  arrowup: ArrowUp,
  sort: ArrowUpDown,
  arrowdown: ArrowDown,
  trophy: Trophy,
  flame: Flame,
  weight: Dumbbell,
  clock: Clock,
  play: Play,
  external: ExternalLink,
  volume: Volume2,
  novideo: VideoOff,
  home: House,
  arrow: ArrowRight,
  history: History,
  info: Info,
  spec: Shapes,
} satisfies Record<string, LucideIcon>;

export type IconName = keyof typeof ICONS;

export function Icon({ name, className = 'i' }: { name: IconName; className?: string }) {
  const C = ICONS[name];
  return <C className={className} aria-hidden="true" />;
}
